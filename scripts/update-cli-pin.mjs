import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

// Draft tooling ("protocol first, consumer second"): generates the runtime-pin.json
// update and PR content that the respire-cli repository consumes after this
// repository publishes a new runtime release.
//
// Usage:
//   node scripts/update-cli-pin.mjs <X.Y.Z> [--out <dir>] [--accept <range>] [--from-builds <dir>]
//
// Contract (docs/version-contract.md):
//   { "required": "X.Y.Z", "accept": ">=X.Y.Z,<2.0.0" }
//   - `required` is the exact pin used by the CLI automatic download.
//   - `accept` keeps an already-installed runtime without forced replacement.
// The CLI pin may only reference an already published runtime release: the
// runtime repository always releases first, the CLI repository second.

const RELEASE_TARGETS = ['x86_64-unknown-linux-gnu', 'aarch64-unknown-linux-gnu', 'x86_64-unknown-linux-musl',
  'aarch64-unknown-linux-musl', 'aarch64-apple-darwin', 'x86_64-pc-windows-msvc', 'aarch64-pc-windows-msvc'];

const args = process.argv.slice(2);
const version = args.find(arg => /^\d+\.\d+\.\d+$/.test(arg));
if (!version) throw new Error('Usage: update-cli-pin.mjs <X.Y.Z> [--out <dir>] [--accept <range>] [--from-builds <dir>]');
const flag = (name, fallback) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : fallback;
};
const out = resolve(flag('--out', join('target', 'runtime-pin-update')));
const accept = flag('--accept', `>=${version},<2.0.0`);
const builds = flag('--from-builds', '');

if (accept === '' || !accept.includes(version)) throw new Error('The accept range must admit the pinned version');

// Optional cross-check: when the release assets were downloaded locally, verify
// every triple's runtime-build report agrees with the pinned version.
const digests = {};
if (builds) {
  for (const target of RELEASE_TARGETS) {
    const path = join(resolve(builds), `runtime-build-${target}.json`);
    if (!existsSync(path)) throw new Error(`Missing ${path}; download all release assets first`);
    const report = JSON.parse(readFileSync(path, 'utf8'));
    if (report.schema_version !== 1 && report.schema_version !== 2) throw new Error(`Unsupported schema in ${path}`);
    if (report.target_triple !== undefined && report.triple !== undefined && report.target_triple !== report.triple) {
      throw new Error(`Conflicting target aliases in ${path}`);
    }
    if (report.archive_sha256 !== undefined && report.sha256 !== undefined && report.archive_sha256 !== report.sha256) {
      throw new Error(`Conflicting archive aliases in ${path}`);
    }
    const targetTriple = report.target_triple ?? report.triple;
    const archiveDigest = report.archive_sha256 ?? report.sha256;
    if (report.runtime_version !== version || targetTriple !== target) throw new Error(`Build report mismatch in ${path}`);
    const binaryFile = `rsrs-runtime-${target}${target.includes('windows') ? '.exe' : ''}`;
    if (report.binary_file !== binaryFile || !/^[a-f0-9]{64}$/.test(report.binary_sha256 || '')) {
      throw new Error(`Invalid binary identity/digest in ${path}`);
    }
    if (report.schema_version === 2 && report.archive_file !== `rsrs-runtime-${target}.tar.gz`) {
      throw new Error(`Invalid archive file in ${path}`);
    }
    if (!/^[a-f0-9]{64}$/.test(archiveDigest || '')) throw new Error(`Invalid archive digest in ${path}`);
    digests[target] = archiveDigest;
  }
  const unique = new Set(Object.values(digests));
  if (unique.size !== RELEASE_TARGETS.length) throw new Error('Duplicate archive digest across targets; refuse to publish a pin for ambiguous assets');
}

const pin = { schema_version: 1, required: version, accept };
const table = Object.entries(digests).map(([target, digest]) => `| ${target} | \`${digest}\` |`).join('\n');
const title = `Update runtime pin to v${version}`;
const body = [
  'Runtime pin update: protocol/consumer order respected.',
  '',
  `- Runtime release \`v${version}\` of \`risense-ai/respire-runtime\` ${builds ? 'is published with verified assets (digests below)' : 'must already be published; verify before merging'}.`,
  `- This repository (respire-cli) releases **after** merging this PR; its pin may only reference the existing runtime release.`,
  `- New pin: \`required = ${version}\`, \`accept = ${accept}\`.`,
  '- Automatic download installs the `required` version exactly; an installed runtime inside the `accept` range is reused without forced replacement.',
  '- Place `runtime-pin.json` at this repository root (or update the existing file) and keep the schema_version field.',
  '',
  ...(builds ? [`### Release archive digests (runtime-build-<triple>.json)`, '', '| Triple | tar.gz SHA-256 |', '| --- | --- |', table, ''] : []),
  'Generated by `risense-ai/respire-runtime` `scripts/update-cli-pin.mjs`.'
].join('\n');

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'runtime-pin.json'), JSON.stringify(pin, null, 2) + '\n');
writeFileSync(join(out, 'pr-title.txt'), title + '\n');
writeFileSync(join(out, 'pr-body.md'), body + '\n');
console.log(`Generated runtime pin update for v${version}:`);
console.log(`  ${join(out, 'runtime-pin.json')}`);
console.log(`  ${join(out, 'pr-title.txt')}`);
console.log(`  ${join(out, 'pr-body.md')}`);
